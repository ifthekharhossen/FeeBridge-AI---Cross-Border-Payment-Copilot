"""Agent orchestrator.

LLM mode : the model picks tools; Python runs them; the model explains the results.
Demo mode: deterministic keyword routing picks the tools (clearly labelled, no AI model used).
In both modes the structured breakdown (numbers, checks, checklist) is built from tool output only.
"""
from __future__ import annotations

import json
import logging
import re
import time
from datetime import date, datetime
from typing import Any

from .config import Settings
from .llm_providers import LLMError, build_provider
from .privacy import Redactor
from .schemas import ChatRequest, PaymentPlanInput
from .tools import TOOL_NAMES, TOOL_SPECS, ToolContext, ToolRun, money, run_tool

log = logging.getLogger("feebridge.agent")

DISCLAIMER = (
    "FeeBridge uses illustrative sample rates, fees and university records. Nothing here is a live quote, "
    "financial advice, or a payment instruction. FeeBridge cannot send money. Verify everything with your "
    "bank and university before paying."
)
DEMO_LABEL = "[DEMO MODE: no AI model connected. This reply is generated by deterministic rules and sample data.]"
FALLBACK_LABEL = "[DEMO MODE (fallback): the AI model could not be reached, so deterministic sample logic was used.]"

SYSTEM_PROMPT = """You are FeeBridge, a planning copilot for international students paying university fees.
Rules you must follow:
- Use the tools for every number, rate, fee, instruction check or checklist. Never invent exchange rates, fees, account details, deadlines or university rules.
- All rates, fees and university records are ILLUSTRATIVE SAMPLE DATA, not live quotes. Say so when you quote figures.
- You cannot send money, make payments, or contact banks. Never say or imply a payment was sent or will be sent by you.
- If details are missing (amount, currency, university, payment reference, deadline), say what is missing and ask for it.
- Do not guess payment details the user did not provide. Do not pass values to check_payment_instructions that the user did not type.
- Remind the student to verify everything with their bank and university before sending money.
- Write plain text only: no markdown, no asterisks, no headings. Keep it under 170 words. The app shows tool results in separate panels, so summarise the key points instead of repeating every number.
Tools default to the student's current payment plan, so you may call them with no arguments."""


def _now_label() -> str:
    return datetime.now().strftime("%I:%M %p").lstrip("0")


def _plan_context(p: PaymentPlanInput) -> str:
    return (
        "Current payment plan (from the app form): "
        f"{p.payment_purpose}, {money(p.tuition_amount, p.tuition_currency)} to {p.university_name or p.university_id} "
        f"(id {p.university_id}) in {p.destination_country}; paying from {p.origin_country} in {p.source_currency}; "
        f"deadline {p.payment_deadline}; student {p.student_name or 'unknown'} (ID {p.student_id or 'unknown'}). "
        f"Today's date is {date.today().isoformat()}."
    )


def _compact(name: str, result: dict[str, Any]) -> dict[str, Any]:
    """Trim tool output sent back to the LLM (the UI gets the full result)."""
    if "error" in result:
        return result
    if name == "compare_transfer_costs":
        keep = ("id", "name", "illustrativeRate", "fixedFeeOriginCurrency", "variableFeePercent",
                "estimatedOriginCost", "estimatedDays", "intermediaryBankRisk", "isLowestCost")
        return {"routes": [{k: r.get(k) for k in keep} for r in result["routes"]],
                "lowestCostRouteId": result["lowestCostRouteId"], "tuitionCurrency": result["tuitionCurrency"],
                "sourceCurrency": result["sourceCurrency"], "note": result["disclaimer"]}
    if name == "check_payment_instructions":
        return {"overallStatus": result["overallStatus"], "summary": result["summary"],
                "nothingEntered": result["nothingEntered"], "expectedReference": result["expectedReference"],
                "requiredReferenceFormat": result["university"]["requiredReferenceFormat"],
                "specialInstructions": result["university"]["specialInstructions"],
                "checks": [{k: c[k] for k in ("label", "status", "explanation")} for c in result["checks"]]}
    return {"initiateBy": result["initiateBy"], "warnings": result["warnings"],
            "tasks": [{k: t[k] for k in ("title", "priority", "dueDate")} for t in result["tasks"]]}


# ---------------------------------------------------------------- structured breakdown

_STATUS_WORD = {"match": "Matches sample record", "missing": "Not provided",
                "needs_confirmation": "Needs confirmation", "mismatch": "Mismatch"}
_STATUS_MAP = {"match": "pass", "missing": "warning", "needs_confirmation": "warning", "mismatch": "mismatch"}


def _by_name(runs: list[ToolRun], name: str) -> ToolRun | None:
    return next((r for r in reversed(runs) if r.name == name and r.ok), None)


def build_breakdown(runs: list[ToolRun], plan: PaymentPlanInput, summary: str) -> dict[str, Any]:
    cost, check, todo = (_by_name(runs, n) for n in TOOL_NAMES)
    out: dict[str, Any] = {"summary": summary}
    findings: list[dict[str, str]] = []
    missing: list[str] = []
    actions: list[str] = []

    if cost:
        r = cost.result
        best = next(x for x in r["routes"] if x["id"] == r["lowestCostRouteId"])
        out["costOverview"] = {
            "sourceAmount": best["estimatedOriginCost"], "sourceCurrency": r["sourceCurrency"],
            "targetAmount": r["tuitionAmount"], "targetCurrency": r["tuitionCurrency"],
            "estimatedRate": best["illustrativeRate"],
            "feeSummary": (f"{best['name']}: est. total ~{money(best['estimatedOriginCost'], r['sourceCurrency'])} "
                           f"(illustrative rate 1 {r['tuitionCurrency']} = {best['illustrativeRate']} {r['sourceCurrency']}). "
                           "Sample data, not a live quote."),
        }
        if not check:
            for x in r["routes"]:
                findings.append({
                    "status": "warning" if x["id"] == "direct_bank" else "pass",
                    "title": x["name"],
                    "detail": f"Est. total ~{money(x['estimatedOriginCost'], r['sourceCurrency'])} | {x['estimatedDays']} | "
                              f"intermediary risk: {x['intermediaryBankRisk']}",
                })
        else:
            findings.append({"status": "warning", "title": "Intermediary deduction alert",
                             "detail": "Commercial bank wires can lose a fee to intermediary banks en route, risking a short payment. "
                                       "Ask your bank about charge options."})

    if check:
        r = check.result
        u = r["university"]
        if r["nothingEntered"]:
            findings.insert(0, {"status": "pass", "title": "Official sample instructions loaded",
                                "detail": f"{u['officialBeneficiaryName']} | {u['officialBankName']} | SWIFT {u['officialSwiftBic']}"})
            findings.insert(1, {"status": "warning", "title": "Payment Reference (Field 70)",
                                "detail": f"Required format {u['requiredReferenceFormat']}; expected for you: {r['expectedReference']}. "
                                          f"{u['specialInstructions']}"})
            missing.append("Your draft payment details (beneficiary, bank, account, SWIFT/BIC, reference) have not been entered, so nothing was verified")
            actions.append("Enter your draft wire details in Payment Verification to check them")
        else:
            for i, c in enumerate(r["checks"]):
                findings.insert(i, {"status": _STATUS_MAP[c["status"]],
                                    "title": f"{c['label']}: {_STATUS_WORD[c['status']]}",
                                    "detail": f"{c['explanation']} {c['guidance']}".strip()})
                if c["status"] == "missing":
                    missing.append(f"{c['label']} not provided")

    if todo:
        r = todo.result
        missing += r["warnings"]
        actions += [f"{t['title']} (by {t['dueDate']})" for t in r["tasks"][:6]]
    if not actions:
        actions = ["Compare routes in Compare Transfer Costs", "Verify bank details in Payment Verification"]

    if findings:
        out["verificationFindings"] = findings
    if missing:
        out["missingItems"] = missing
    out["actionItems"] = actions
    return out


# ---------------------------------------------------------------- demo (deterministic) mode

def _intent(msg: str) -> str:
    m = msg.lower()
    has = lambda *w: any(re.search(rf"\b{x}", m) for x in w)  # noqa: E731
    if has("plan"):
        return "plan"
    if has("compare", "cost", "fee", "rate", "cheap"):
        return "compare"
    if has("instruction", "verify", r"check\b", "bank", "swift", "reference", "beneficiary"):
        return "instructions"
    if has("checklist", "prepare", "steps", "tasks", "todo"):
        return "checklist"
    if has("tuition", "bangladesh", "china", "pay", "payment", r"8,?000"):
        return "plan"
    return "general"


def _demo(req: ChatRequest, ctx: ToolContext, label: str) -> tuple[str, str, list[ToolRun]]:
    p, runs = req.plan, []
    ref = re.search(r"\b[A-Za-z]{2,8}(?:-[A-Za-z0-9]+){1,3}\b", req.message)
    intent = _intent(req.message.replace(ref.group(0), " ") if ref else req.message)  # a reference like TUITION-FEE is not an intent
    uni = p.university_name or p.university_id
    step = lambda n, a=None: runs.append(run_tool(n, a or {}, ctx, seq=len(runs) + 1))  # noqa: E731

    if intent in {"plan", "compare"}:
        step("compare_transfer_costs")
    if intent in {"plan", "instructions"}:
        step("check_payment_instructions", {"reference": ref.group(0)} if ref else {})
    if intent in {"plan", "checklist"}:
        issues = []
        chk = _by_name(runs, "check_payment_instructions")
        if chk:
            issues = [f"{c['label']}: {c['explanation']}" for c in chk.result["checks"]
                      if c["status"] in {"mismatch"}]
        step("create_payment_checklist", {"unresolved_issues": issues})

    amt = money(p.tuition_amount, p.tuition_currency)
    if intent == "plan":
        content = f"I ran a payment plan for {amt} to {uni} from {p.origin_country}: route costs, the university's payment instructions, and a dated checklist."
        summary = f"Plan for {p.student_name or 'the student'}: compared 3 sample routes, loaded the sample payment instructions, and built a checklist. Figures are illustrative only."
    elif intent == "compare":
        content = f"Here is an illustrative comparison of three transfer routes for {amt} to {uni}:"
        summary = "Compared 3 sample transfer channels. All rates and fees are illustrative planning figures, not live quotes."
    elif intent == "instructions":
        content = f"I checked the payment instructions for {uni} against the sample university record:"
        summary = f"Institution: {uni}. Compared against sample records, not live bank data."
    elif intent == "checklist":
        content = f"Here is a dated preparation checklist for paying {uni} before {p.payment_deadline}:"
        summary = f"Payment deadline: {p.payment_deadline}. The checklist works backwards from this date using illustrative buffers."
    else:
        content = ("I can compare illustrative transfer costs, check payment instructions for your university, "
                   "and build a payment checklist. Try one of the suggestions below, or tell me what you need.")
        summary = f"Context: {p.origin_country} to {p.destination_country} ({uni})."
        return f"{label}\n\n{content}", summary, runs
    return f"{label}\n\n{content}", summary, runs


# ---------------------------------------------------------------- main entry point

async def run_agent(req: ChatRequest, settings: Settings, provider=None, today: date | None = None) -> dict[str, Any]:
    ctx = ToolContext(plan=req.plan, today=today)
    provider = provider if provider is not None else build_provider(settings)
    mode, label, content, summary, runs = "demo", DEMO_LABEL, "", "", []
    error_note: str | None = None

    if provider is not None:
        redactor = Redactor(req.plan, enabled=not settings.llm_send_student_pii)
        runs = []

        def execute(name: str, args: dict[str, Any]) -> str:
            if name not in TOOL_NAMES:
                return json.dumps({"error": f"Unknown tool '{name}'"})
            run = run_tool(name, redactor.restore_obj(args), ctx, seq=len(runs) + 1)
            runs.append(run)
            return json.dumps(redactor.scrub_obj(_compact(name, run.result)), ensure_ascii=False)

        try:
            history = [{"role": "assistant" if h.sender == "assistant" else "user", "content": redactor.scrub(h.content)}
                       for h in req.history]
            text = await provider.converse(
                system=redactor.scrub(SYSTEM_PROMPT + "\n\n" + _plan_context(req.plan)),
                history=history, user_message=redactor.scrub(req.message),
                tools=TOOL_SPECS, execute=execute)
            text = redactor.restore(text)
            text = re.sub(r"[*_#`]{1,3}", "", text).strip()  # frontend renders plain text, not markdown
            if not text:
                raise LLMError("Empty answer from model")
            mode, content = "llm", text
            summary = ("Figures come from FeeBridge's calculation tools using illustrative sample data, "
                       "not live quotes." if runs else "No tools were needed for this question.")
        except LLMError as exc:
            log.warning("LLM call failed: %s", exc)
            if not settings.llm_fallback_to_demo:
                raise
            mode, label, error_note = "demo_fallback", FALLBACK_LABEL, str(exc)
            provider = None

    if provider is None:
        content, summary, runs = _demo(req, ctx, label)

    breakdown = build_breakdown(runs, req.plan, summary)
    now_ms = int(time.time() * 1000)
    reply = {
        "id": f"msg-{now_ms}", "sender": "assistant", "timestamp": _now_label(),
        "content": content, "structuredBreakdown": breakdown,
        "toolExecutions": [r.execution for r in runs],
    }
    todo = _by_name(runs, "create_payment_checklist")
    return {
        "replyMessage": reply,
        "tools": [r.execution for r in runs],
        "mode": mode,
        "provider": settings.resolved_provider if mode == "llm" else None,
        "model": settings.active_model if mode == "llm" else None,
        "checklist": todo.result["tasks"] if todo else None,
        "warning": error_note,
        "disclaimer": DISCLAIMER,
    }
